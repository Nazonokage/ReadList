import { build } from 'esbuild';
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const pieces = [];
for (const [entry, globalName] of [['pdfjs-dist/legacy/build/pdf.worker.mjs', 'pdfjsWorker'], ['pdfjs-dist/legacy/build/pdf.mjs', 'pdfjsLib']]) {
  const result = await build({ entryPoints: [require.resolve(entry)], bundle: true, format: 'iife', globalName, platform: 'browser', target: 'es2020', minify: true, write: false, external: ['node:*', '@napi-rs/canvas'], legalComments: 'inline' });
  pieces.push(result.outputFiles[0].text);
}
await mkdir('src/reader', { recursive: true });
await writeFile('src/reader/pdfRuntime.js', '// Generated by scripts/build-reader-runtime.mjs; bundled offline PDF.js (Apache-2.0).\nexport default ' + JSON.stringify(pieces.join('\n')) + ';\n');
console.log('Offline PDF runtime generated.');

const reflow = (await readFile('src/reader/pdfReflow.js', 'utf8')).replace('export async function', 'async function');
await writeFile('src/reader/pdfReflowRuntime.js', '// Generated reader source; keep as text for native Hermes compatibility.\nexport default ' + JSON.stringify('(' + reflow + ')') + ';\n');
